/**
 * Единственный источник правды про «где мы живём и кто мы» для поисковиков.
 *
 * Всё остальное в src/seo/ считает адреса и разметку отсюда, чтобы канонические
 * ссылки, sitemap, robots и JSON-LD не разъезжались между собой.
 */

/**
 * Боевой адрес лендинга. Прибит константой, а не только к BASE_URL, сознательно:
 *
 *  1. На сервере рядом живут соседние проекты, и то же приложение может
 *     открыться по чужому имени или по IP. Если канонические ссылки собирать от
 *     текущего хоста, у каждой такой двери появится собственная копия страницы.
 *     Абсолютный канонический адрес схлопывает их в одну.
 *  2. В Dockerfile BASE_URL по умолчанию задан как https://makemelook.ai — это
 *     ДРУГОЙ продукт (платформа для покупателей). Поднимать метаданные лендинга
 *     на этот адрес нельзя.
 *
 * Переопределяется переменной SITE_URL, если лендинг когда-нибудь переедет.
 */
export const SITE_URL = (process.env.SITE_URL ?? 'https://b2b.makemelook.ai').replace(/\/+$/, '');

/**
 * Маршруты лендинга. Соответствуют дереву после переезда на корень:
 * src/app/(landing)/page.tsx → «/», src/app/blog/** → «/blog».
 *
 * Если маршруты снова поменяются, правятся только эти три строки: sitemap,
 * канонические адреса, хлебные крошки и JSON-LD собираются отсюда.
 */
export const routes = {
  landing: '/',
  blog: '/blog',
  blogArticle: (slug: string) => `/blog/${slug}`
} as const;

/** Абсолютный адрес — то, что кладём в canonical, sitemap и JSON-LD. */
export function absoluteUrl(pathname: string): string {
  if (/^https?:\/\//.test(pathname)) return pathname;
  return `${SITE_URL}${pathname.startsWith('/') ? pathname : `/${pathname}`}`;
}

