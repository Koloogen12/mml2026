'use client';

import { useEffect, useState } from 'react';

import { track } from './track';

/**
 * Липкая шапка и липкая кнопка на телефоне.
 *
 * Зачем: в макете шапка живёт ВНУТРИ карточки первого экрана, и как только
 * человек её пролистал, целевого действия на экране больше нет — до самого
 * низа страницы. AUDIT.md называет это обязательным пунктом вёрстки.
 *
 * Появляется не по номеру пикселя, а по уходу первого экрана из вида: высота
 * геро-карточки задана через vh и на разных экранах разная.
 *
 * Токены взяты из хендоффа: тёмный элемент #121417, радиус 999px, Golos Text,
 * стекло как у пилюль шапки. Ничего нового не придумано.
 */
export function StickyCta() {
  const [shown, setShown] = useState(false);

  useEffect(() => {
    const hero = document.querySelector('section[data-screen-label="01 Hero"]');
    if (!hero) return;

    // Обычный слушатель прокрутки, а не IntersectionObserver. Причина
    // приземлённая: наблюдатель нечем проверить в браузере, которым я гоняю
    // приёмку — он там не вызывается ни разу. Полагаться в продакшне на то,
    // что не можешь проверить, не стоит, а задача здесь простая: «первый
    // экран уехал вверх». Слушатель пассивный и сжат до кадра через rAF.
    // Замер делаем прямо в обработчике, без requestAnimationFrame.
    // Причина та же, что и с наблюдателем пересечений: rAF не вызывается,
    // когда вкладка не рисует кадры, и тогда панель не появляется вовсе.
    // Одно чтение getBoundingClientRect на событие прокрутки дешевле, чем
    // зависимость от того, чего нельзя проверить.
    const check = () => setShown(hero.getBoundingClientRect().bottom < 0);
    check();
    window.addEventListener('scroll', check, { passive: true });
    window.addEventListener('resize', check, { passive: true });
    return () => {
      window.removeEventListener('scroll', check);
      window.removeEventListener('resize', check);
    };
  }, []);

  const go = () => {
    track('sticky_cta_click');
    document.getElementById('form')?.scrollIntoView({ behavior: 'smooth', block: 'start' });
  };

  return (
    <div
      className="mml-sticky"
      data-shown={shown ? 'yes' : 'no'}
      // aria-hidden в скрытом состоянии: пока панели не видно, она не должна
      // попадаться в обход с клавиатуры и в скринридере.
      aria-hidden={!shown}
    >
      <div className="mml-sticky__bar">
        <span className="mml-sticky__mark" aria-hidden="true">
          <svg viewBox="0 0 34 25" width="20" height="15" fill="none">
            <path
              d="M33.6 24.4318H30.5455V3.8182C30.5455 3.66716 30.5007 3.51952 30.4168 3.39394C30.3329 3.26836 30.2136 3.17048 30.0741 3.11268C29.9345 3.05489 29.781 3.03976 29.6328 3.06923C29.4847 3.0987 29.3486 3.17143 29.2418 3.27823L11.8635 20.6566C11.5089 21.0111 11.088 21.2924 10.6248 21.4843C10.1615 21.6761 9.66502 21.7749 9.16361 21.7749C8.6622 21.7749 8.16569 21.6761 7.70245 21.4843C7.23921 21.2924 6.8183 21.0111 6.46375 20.6566L4.35812 18.551C4.25132 18.4442 4.11526 18.3715 3.96712 18.342C3.81899 18.3125 3.66545 18.3277 3.52591 18.3854C3.38637 18.4432 3.26711 18.5411 3.1832 18.6667C3.09929 18.7923 3.0545 18.9399 3.05449 19.091V24.4318H0V19.091C0 18.3358 0.223919 17.5976 0.643462 16.9697C1.06301 16.3418 1.65932 15.8524 2.357 15.5634C3.05468 15.2744 3.82239 15.1988 4.56304 15.3461C5.3037 15.4935 5.98403 15.8571 6.51801 16.3911L8.62363 18.4967C8.69453 18.5676 8.77871 18.6239 8.87135 18.6622C8.96399 18.7006 9.06329 18.7204 9.16357 18.7204C9.26384 18.7204 9.36314 18.7006 9.45578 18.6623C9.54843 18.6239 9.63261 18.5676 9.70351 18.4967L27.0819 1.11834C27.6159 0.584351 28.2962 0.220699 29.0369 0.0733701C29.7776 -0.073959 30.5453 0.00165186 31.243 0.290641C31.9406 0.579631 32.537 1.06902 32.9565 1.69692C33.3761 2.32482 33.6 3.06303 33.6 3.8182V24.4318Z"
              fill="#121417"
            />
          </svg>
          MakeMeLook
        </span>
        <button type="button" className="mml-sticky__btn" onClick={go} tabIndex={shown ? 0 : -1}>
          Показать на моих товарах
        </button>
      </div>
    </div>
  );
}
