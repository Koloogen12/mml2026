/** Точки замера вовлечённости на лендинге.
 *
 * В проекте уже стоит Яндекс.Метрика (счётчик инициализируется в корневом
 * layout). Своей обвязки не заводим — шлём цели в неё же.
 *
 * Что меряем и почему именно это: AUDIT.md называет лучшими индикаторами
 * вовлечённости взаимодействия, а не скроллы — ставки в угадайке, движение
 * ползунков калькулятора, переключение слоёв и табов, отправку форм.
 * Скролл до блока показывает, что человек долистал, а не что ему интересно.
 */
const COUNTER = 97809376;

type Ym = (id: number, action: string, target: string, params?: Record<string, unknown>) => void;

export function track(goal: string, params?: Record<string, unknown>) {
  if (typeof window === 'undefined') return;
  const ym = (window as unknown as { ym?: Ym }).ym;
  // Счётчик может не успеть инициализироваться или быть заблокирован —
  // это не повод ронять обработчик формы.
  try {
    ym?.(COUNTER, 'reachGoal', goal, params);
  } catch {
    /* аналитика никогда не важнее действия пользователя */
  }
}
