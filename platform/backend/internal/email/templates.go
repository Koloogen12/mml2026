package email

// Шаблоны по макету «MakeMeLook Emails». Здесь только письма, у которых уже
// есть реальный триггер в бэкенде. Остальные из макета (U4 примерка, U6
// подборка недели, P3/P9 синк каталога, P5 нудж «нет каталога», P6 сводка) ждут
// своих событий; заводить шаблон без триггера значит держать мёртвый код.

// LoginCode — U1 (покупатель) / P1 (партнёр).
// Триггер: POST /auth/request-code. Без CTA: код вводят в открытой вкладке.
func LoginCode(code string, partner bool) Mail {
	who := "MakeMeLook"
	reason := "Вы получили это письмо, потому что запросили код для входа в MakeMeLook."
	if partner {
		who = "кабинет партнёра MakeMeLook"
		reason = "Вы получили это письмо, потому что запросили код для входа в кабинет партнёра MakeMeLook."
	}
	body := h1("Ваш код для входа") +
		p("Введите его в открытой вкладке "+who+", чтобы завершить вход.") +
		codePlate(code) +
		mutedCenter("Код действует 10 минут") +
		divider() +
		note("Если это были не вы — просто проигнорируйте письмо. Без ввода кода вход не произойдёт.")

	return Mail{
		// Код в теме — чтобы прочитать из уведомления, не открывая письмо.
		Subject: "Код входа: " + spaced(code),
		HTML:    wrap(body, layoutOpts{preheader: "Код " + spaced(code) + " · действует 10 минут", reason: reason}),
		Text: plain(
			"Ваш код для входа в "+who+": "+code,
			"",
			"Код действует 10 минут.",
			"Если это были не вы — просто проигнорируйте письмо: без ввода кода вход не произойдёт.",
		),
	}
}

// Welcome — U2. Триггер: первый успешный вход покупателя (is_new).
func Welcome(name, appURL string) Mail {
	hello := "Добро пожаловать"
	if name != "" {
		hello = "Добро пожаловать, " + name
	}
	body := h1(hello) +
		p("Опишите повод словами — ассистент соберёт образ из того, что вам подойдёт, и покажет вещь на вас до покупки.") +
		p("Чем больше вы сохраняете и уточняете, тем точнее подбор: паспорт стиля учится на ваших ответах.") +
		button("Собрать первый образ", appURL) +
		divider() +
		note("Паспорт стиля можно поправить в любой момент — следующая выдача учтёт правки.")

	return Mail{
		Subject: "Вы в MakeMeLook",
		HTML: wrap(body, layoutOpts{
			preheader: "Опишите повод — соберём образ и покажем его на вас",
			reason:    "Вы получили это письмо, потому что создали аккаунт в MakeMeLook.",
		}),
		Text: plain(
			hello+"!",
			"",
			"Опишите повод словами — ассистент соберёт образ из того, что вам подойдёт,",
			"и покажет вещь на вас до покупки.",
			"",
			"Собрать первый образ: "+appURL,
		),
	}
}

