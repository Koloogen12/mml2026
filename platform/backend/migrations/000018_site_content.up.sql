-- Контент главной страницы, редактируемый из админки: табы, популярные
-- запросы по полу, плейсхолдеры, плитки трендов, блоки «как это работает».
-- Ключ-значение: содержимое главной — это несколько независимых блоков,
-- под каждый заводить таблицу с колонками не за что.
-- Дефолты живут в коде (internal/content/content.go), в базе — только то,
-- что человек реально переопределил. Пустая таблица = страница как из коробки.
CREATE TABLE site_content (
  key        TEXT PRIMARY KEY,
  value      JSONB NOT NULL,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
